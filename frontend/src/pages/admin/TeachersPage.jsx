import { useCallback, useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import * as admin from '../../services/admin.js';
import { PageHeader, Pagination, StatusBadge, Notice } from '../../components/ui/PageHeader.jsx';
import { Select } from '../../components/forms/Field.jsx';

export default function TeachersPage() {
  const [search, setSearch] = useState('');
  const [query, setQuery] = useState('');
  const [status, setStatus] = useState('');
  const [page, setPage] = useState(1);
  const [data, setData] = useState({ rows: [], meta: null });
  const [state, setState] = useState('loading');
  const [error, setError] = useState('');

  useEffect(() => {
    const timer = setTimeout(() => {
      setQuery(search);
      setPage(1);
    }, 300);
    return () => clearTimeout(timer);
  }, [search]);

  const load = useCallback(async () => {
    setState('loading');
    try {
      setData(await admin.listTeachers({ search: query || undefined, status: status || undefined, page, limit: 10 }));
      setState('ready');
    } catch (requestError) {
      setState('error');
      setError(requestError.response?.data?.error?.message || 'Could not load teachers.');
    }
  }, [query, status, page]);

  useEffect(() => {
    load();
  }, [load]);

  const meta = data.meta;
  const filtered = Boolean(query || status);
  const firstRow = meta && data.rows.length ? (meta.page - 1) * meta.limit + 1 : 0;
  const lastRow = meta && data.rows.length ? firstRow + data.rows.length - 1 : 0;

  return (
    <div className="page">
      <PageHeader
        title="Teachers"
        subtitle="Employee IDs are generated by the database (VVT-0001)."
        actions={
          <>
            {meta && (
              <span className="summary-chip">
                <strong>{meta.total}</strong>{' '}
                {filtered
                  ? meta.total === 1 ? 'match' : 'matches'
                  : meta.total === 1 ? 'teacher' : 'teachers'}
              </span>
            )}
            <Link className="btn-primary" to="/admin/teachers/new">
              <i className="bi bi-person-badge" aria-hidden="true" /> Add teacher
            </Link>
          </>
        }
      />

      {error && <Notice kind="error" onClose={() => setError('')}>{error}</Notice>}

      <section className="section-card list-screen">
        <div className="filters">
          <div className="filters__search">
            <i className="bi bi-search" aria-hidden="true" />
            <input type="search" placeholder="Search by name, employee ID or email"
              value={search} onChange={(event) => setSearch(event.target.value)}
              aria-label="Search teachers" />
          </div>
          <Select name="status" value={status} placeholder="Any status"
            onChange={(event) => { setStatus(event.target.value); setPage(1); }}
            options={[
              { value: 'active', label: 'Active' },
              { value: 'on_leave', label: 'On leave' },
              { value: 'resigned', label: 'Resigned' },
            ]} />
        </div>

        {state === 'loading' && (
          <div className="list-loading">
            <span className="spinner" aria-hidden="true" />
            <span>Loading teachers…</span>
          </div>
        )}

        {state !== 'loading' && data.rows.length === 0 && (
          <div className="empty-state">
            <span className="empty-state__icon">
              <i className={`bi ${filtered ? 'bi-funnel' : 'bi-person-badge'}`} aria-hidden="true" />
            </span>
            {filtered ? (
              <>
                <strong>No teacher matches these filters</strong>
                <span>
                  {query ? `Nothing found for “${query}”. ` : ''}
                  Try a different name, employee ID or status.
                </span>
              </>
            ) : (
              <>
                <strong>No teachers yet</strong>
                <span>Staff you add get an employee ID and a login with a temporary password.</span>
                <Link className="btn-primary empty-state__action" to="/admin/teachers/new">
                  <i className="bi bi-person-badge" aria-hidden="true" /> Add the first teacher
                </Link>
              </>
            )}
          </div>
        )}

        {state !== 'loading' && data.rows.length > 0 && (
          <div className="table-wrap">
            <table className="data-table">
              <thead>
                <tr>
                  <th className="col-id">Employee ID</th>
                  <th>Name</th>
                  <th className="col-num align-right">Subjects</th>
                  <th>Class teacher</th>
                  <th className="col-status">Status</th>
                  <th className="col-actions align-right">Actions</th>
                </tr>
              </thead>
              <tbody>
                {data.rows.map((teacher) => (
                  <tr key={teacher.id}>
                    <td className="mono" data-label="Employee ID">{teacher.employeeId}</td>
                    <td data-label="Name">
                      <Link to={`/admin/teachers/${teacher.id}`}>{teacher.name}</Link>
                    </td>
                    <td className="align-right num" data-label="Subjects">{teacher.subjectCount}</td>
                    <td data-label="Class teacher">
                      {teacher.classTeacherOf || <span className="muted">—</span>}
                    </td>
                    <td data-label="Status"><StatusBadge status={teacher.status} /></td>
                    <td data-label="Actions" className="align-right">
                      <span className="row-actions">
                        <Link className="btn-ghost btn--sm" to={`/admin/teachers/${teacher.id}`}>
                          View
                        </Link>
                      </span>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}

        {state !== 'loading' && (
          <div className="list-foot">
            <span className="list-foot__count">
              {data.rows.length === 0
                ? filtered ? 'No match for the current filters' : 'No records yet'
                : `Showing ${firstRow}–${lastRow} of ${meta?.total ?? data.rows.length}`}
            </span>
            <Pagination meta={data.meta} onPage={setPage} />
          </div>
        )}
      </section>
    </div>
  );
}
