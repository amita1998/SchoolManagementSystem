import { useCallback, useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import * as admin from '../../services/admin.js';
import { PageHeader, Pagination, StatusBadge, Notice } from '../../components/ui/PageHeader.jsx';
import { Select } from '../../components/forms/Field.jsx';

export default function TeachersPage() {
  const [search, setSearch] = useState('');
  const [query, setQuery] = useState('');
  const [status, setStatus] = useState('');
  const [page, setPage] = useState(1);
  const [data, setData] = useState({ rows: [], meta: null });
  const [state, setState] = useState('loading');
  const [error, setError] = useState('');

  useEffect(() => {
    const timer = setTimeout(() => {
      setQuery(search);
      setPage(1);
    }, 300);
    return () => clearTimeout(timer);
  }, [search]);

  const load = useCallback(async () => {
    setState('loading');
    try {
      setData(await admin.listTeachers({ search: query || undefined, status: status || undefined, page, limit: 10 }));
      setState('ready');
    } catch (requestError) {
      setState('error');
      setError(requestError.response?.data?.error?.message || 'Could not load teachers.');
    }
  }, [query, status, page]);

  useEffect(() => {
    load();
  }, [load]);

  return (
    <div className="page">
      <PageHeader
        title="Teachers"
        subtitle="Employee IDs are generated by the database (VVT-0001)."
        actions={
          <Link className="btn-primary" to="/admin/teachers/new">
            <i className="bi bi-person-badge" aria-hidden="true" /> Add teacher
          </Link>
        }
      />

      {error && <Notice kind="error" onClose={() => setError('')}>{error}</Notice>}

      <section className="section-card">
        <div className="filters">
          <div className="filters__search">
            <i className="bi bi-search" aria-hidden="true" />
            <input type="search" placeholder="Search by name, employee ID or email"
              value={search} onChange={(event) => setSearch(event.target.value)}
              aria-label="Search teachers" />
          </div>
          <Select name="status" value={status} placeholder="Any status"
            onChange={(event) => { setStatus(event.target.value); setPage(1); }}
            options={[
              { value: 'active', label: 'Active' },
              { value: 'on_leave', label: 'On leave' },
              { value: 'resigned', label: 'Resigned' },
            ]} />
        </div>

        {state === 'loading' && <p className="table-empty">Loading teachers…</p>}
        {state !== 'loading' && data.rows.length === 0 && (
          <div className="table-empty">
            No teachers yet. <Link to="/admin/teachers/new">Add the first teacher</Link>.
          </div>
        )}

        {state !== 'loading' && data.rows.length > 0 && (
          <div className="table-wrap">
            <table className="data-table">
              <thead>
                <tr>
                  <th>Employee ID</th>
                  <th>Name</th>
                  <th>Subjects</th>
                  <th>Class teacher</th>
                  <th>Status</th>
                  <th />
                </tr>
              </thead>
              <tbody>
                {data.rows.map((teacher) => (
                  <tr key={teacher.id}>
                    <td className="mono">{teacher.employeeId}</td>
                    <td><Link to={`/admin/teachers/${teacher.id}`}>{teacher.name}</Link></td>
                    <td>{teacher.subjectCount}</td>
                    <td>{teacher.classTeacherOf || <span className="muted">—</span>}</td>
                    <td><StatusBadge status={teacher.status} /></td>
                    <td className="align-right">
                      <Link className="link-button" to={`/admin/teachers/${teacher.id}`}>View</Link>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}

        <Pagination meta={data.meta} onPage={setPage} />
      </section>
    </div>
  );
}
