import { useCallback, useEffect, useMemo, useState } from 'react';
import { Link } from 'react-router-dom';
import * as admin from '../../services/admin.js';
import { PageHeader, Pagination, StatusBadge, Notice } from '../../components/ui/PageHeader.jsx';
import { Select } from '../../components/forms/Field.jsx';

const STATUS_OPTIONS = [
  { value: 'active', label: 'Active' },
  { value: 'new_admission', label: 'New admission' },
  { value: 'promoted', label: 'Promoted' },
  { value: 'academic_year_renewed', label: 'Year renewed' },
  { value: 'graduated', label: 'Graduated' },
  { value: 'transferred', label: 'Transferred' },
  { value: 'withdrawn', label: 'Withdrawn' },
  { value: 'suspended', label: 'Suspended' },
];

export default function StudentsPage() {
  const [options, setOptions] = useState(null);
  const [search, setSearch] = useState('');
  const [query, setQuery] = useState('');
  const [classId, setClassId] = useState('');
  const [sectionId, setSectionId] = useState('');
  const [status, setStatus] = useState('');
  const [page, setPage] = useState(1);
  const [data, setData] = useState({ rows: [], meta: null });
  const [state, setState] = useState('loading');
  const [error, setError] = useState('');

  useEffect(() => {
    admin.getOptions().then(setOptions).catch(() => {});
  }, []);

  useEffect(() => {
    const timer = setTimeout(() => {
      setQuery(search);
      setPage(1);
    }, 300);
    return () => clearTimeout(timer);
  }, [search]);

  const load = useCallback(async () => {
    setState('loading');
    setError('');
    try {
      const result = await admin.listStudents({
        search: query || undefined,
        classId: classId || undefined,
        sectionId: sectionId || undefined,
        status: status || undefined,
        page,
        limit: 10,
      });
      setData(result);
      setState('ready');
    } catch (requestError) {
      setState('error');
      setError(requestError.response?.data?.error?.message || 'Could not load students.');
    }
  }, [query, classId, sectionId, status, page]);

  useEffect(() => {
    load();
  }, [load]);

  const classOptions = useMemo(
    () => (options?.classes || []).map((item) => ({ value: item.id, label: item.name })),
    [options],
  );
  const sectionOptions = useMemo(() => {
    const klass = options?.classes.find((item) => String(item.id) === String(classId));
    return (klass?.sections || []).map((item) => ({ value: item.id, label: `Section ${item.name}` }));
  }, [options, classId]);

  const meta = data.meta;
  const filtered = Boolean(query || classId || status);
  const firstRow = meta && data.rows.length ? (meta.page - 1) * meta.limit + 1 : 0;
  const lastRow = meta && data.rows.length ? firstRow + data.rows.length - 1 : 0;

  return (
    <div className="page">
      <PageHeader
        title="Students"
        subtitle="Admissions, class placement and lifecycle. Admission IDs are generated by the database."
        actions={
          <>
            {meta && (
              <span className="summary-chip">
                <strong>{meta.total}</strong>{' '}
                {filtered
                  ? meta.total === 1 ? 'match' : 'matches'
                  : meta.total === 1 ? 'student' : 'students'}
              </span>
            )}
            <Link className="btn-primary" to="/admin/students/new">
              <i className="bi bi-person-plus" aria-hidden="true" /> Add student
            </Link>
          </>
        }
      />

      {error && <Notice kind="error" onClose={() => setError('')}>{error}</Notice>}

      <section className="section-card list-screen">
        <div className="filters">
          <div className="filters__search">
            <i className="bi bi-search" aria-hidden="true" />
            <input
              type="search"
              placeholder="Search by name or Admission ID"
              value={search}
              onChange={(event) => setSearch(event.target.value)}
              aria-label="Search students"
            />
          </div>
          <Select
            name="classId"
            value={classId}
            onChange={(event) => {
              setClassId(event.target.value);
              setSectionId('');
              setPage(1);
            }}
            placeholder="All classes"
            options={classOptions}
          />
          <Select
            name="sectionId"
            value={sectionId}
            onChange={(event) => {
              setSectionId(event.target.value);
              setPage(1);
            }}
            placeholder="All sections"
            options={sectionOptions}
            disabled={!classId}
          />
          <Select
            name="status"
            value={status}
            onChange={(event) => {
              setStatus(event.target.value);
              setPage(1);
            }}
            placeholder="Any status"
            options={STATUS_OPTIONS}
          />
        </div>

        {state === 'loading' && (
          <div className="list-loading">
            <span className="spinner" aria-hidden="true" />
            <span>Loading students…</span>
          </div>
        )}

        {state !== 'loading' && data.rows.length === 0 && (
          <div className="empty-state">
            <span className="empty-state__icon">
              <i className={`bi ${filtered ? 'bi-funnel' : 'bi-people'}`} aria-hidden="true" />
            </span>
            {filtered ? (
              <>
                <strong>No student matches these filters</strong>
                <span>
                  {query ? `Nothing found for “${query}”. ` : ''}
                  Try a different name, class or status.
                </span>
              </>
            ) : (
              <>
                <strong>No students yet</strong>
                <span>Admissions you record will be listed here with their class placement.</span>
                <Link className="btn-primary empty-state__action" to="/admin/students/new">
                  <i className="bi bi-person-plus" aria-hidden="true" /> Admit the first student
                </Link>
              </>
            )}
          </div>
        )}

        {state !== 'loading' && data.rows.length > 0 && (
          <div className="table-wrap">
            <table className="data-table">
              <thead>
                <tr>
                  <th className="col-id">Admission ID</th>
                  <th>Name</th>
                  <th className="col-class">Class</th>
                  <th className="col-guardian">Guardian mobile</th>
                  <th className="col-status">Status</th>
                  <th className="col-actions align-right">Actions</th>
                </tr>
              </thead>
              <tbody>
                {data.rows.map((student) => (
                  <tr key={student.id}>
                    <td className="mono" data-label="Admission ID">{student.admissionId}</td>
                    <td data-label="Name">
                      <Link to={`/admin/students/${student.id}`}>{student.name}</Link>
                    </td>
                    <td data-label="Class">
                      {student.className ? (
                        <>
                          {student.className}
                          {student.sectionName && <span className="muted"> · {student.sectionName}</span>}
                        </>
                      ) : (
                        <span className="muted">Not enrolled</span>
                      )}
                    </td>
                    <td data-label="Guardian mobile">
                      {student.guardianMobile ? (
                        <span className="mono">{student.guardianMobile}</span>
                      ) : (
                        <span className="muted">—</span>
                      )}
                    </td>
                    <td data-label="Status">
                      <StatusBadge status={student.status} />
                    </td>
                    <td data-label="Actions" className="align-right">
                      <span className="row-actions">
                        <Link className="btn-ghost btn--sm" to={`/admin/students/${student.id}`}>
                          View
                        </Link>
                        <Link className="btn-ghost btn--sm" to={`/admin/students/${student.id}?edit=1`}>
                          Edit
                        </Link>
                      </span>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}

        {state !== 'loading' && (
          <div className="list-foot">
            <span className="list-foot__count">
              {data.rows.length === 0
                ? filtered ? 'No match for the current filters' : 'No records yet'
                : `Showing ${firstRow}–${lastRow} of ${meta?.total ?? data.rows.length}`}
            </span>
            <Pagination meta={data.meta} onPage={setPage} />
          </div>
        )}
      </section>
    </div>
  );
}
